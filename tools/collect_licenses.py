"""Write THIRD_PARTY_NOTICES.md from the license metadata of the installed packages that end up in the build.

    python tools/collect_licenses.py [output.md]

The text is whatever each package declares in its own metadata (License-Expression / License / classifiers); nothing is filled in from
memory. Packages that declare nothing are listed as 'not declared in the package metadata - check the upstream project'.
"""
import os
import sys
from importlib import metadata

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PACKAGES = [
    ("sam2", "SAM 2 code (model weights are downloaded by the user, see models/README.md)"),
    ("nudenet", "NudeNet (also supplies the bundled 320n.onnx detector model)"),
    ("torch", "PyTorch (CUDA runtime libraries are bundled with the wheel)"),
    ("torchvision", ""),
    ("onnxruntime", "ONNX Runtime"),
    ("opencv-python", "OpenCV (the wheel bundles its own FFmpeg libraries)"),
    ("numpy", ""),
    ("pillow", ""),
    ("psutil", ""),
    ("hydra-core", ""),
    ("omegaconf", ""),
    ("iopath", ""),
    ("tqdm", ""),
    ("PyYAML", ""),
    ("PySide6-Essentials", "Qt for Python (desktop app)"),
    ("shiboken6", ""),
    ("pyinstaller", "build tool; its bootloader is part of the exe"),
]


def declared_license(md) -> str:
    expr = md.get("License-Expression")
    if expr:
        return expr.strip()
    lic = (md.get("License") or "").strip()
    if lic and lic.upper() != "UNKNOWN":
        first = lic.splitlines()[0].strip()
        return first if len(lic) < 120 else (first[:100] + " ... (full text in the package)")
    cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or [] if c.startswith("License ::")]
    return "; ".join(cls) if cls else ""


def main(out_path: str) -> int:
    rows, missing = [], []
    for name, note in PACKAGES:
        try:
            md = metadata.metadata(name)
            version = metadata.version(name)
        except metadata.PackageNotFoundError:
            missing.append(name)
            continue
        lic = declared_license(md)
        home = md.get("Home-page") or next((u.split(",")[-1].strip() for u in md.get_all("Project-URL") or []), "")
        if name == "sam2" and "facebookresearch" not in home.lower():
            note += (" **PROVENANCE: this PyPI package is not published by Meta** (author " + (md.get("Author") or "unknown") + "); "
                     "its sam2/ source files were compared with Meta's official repository (commit 2b90b9f) and are identical apart from line endings. See README, section 'SAM 2 package provenance'.")
        rows.append((md["Name"], version, lic or "not declared in the package metadata - check the upstream project", home, note))
    lines = [
        "# Third-party components",
        "",
        "Generated by `tools/collect_licenses.py` from the license metadata of the packages installed in the build environment. "
        "It is a starting point for your own license review, not legal advice.",
        "",
        "| package | version | declared license | project | note |",
        "|---|---|---|---|---|",
    ]
    for n, v, lic, home, note in rows:
        lines.append(f"| {n} | {v} | {lic.replace('|', '/')} | {home} | {note} |")
    lines += [
        "",
        "## Not included in the build (you supply them)",
        "- **SAM 2.1 model weights** (`sam2.1_hiera_*.pt`): download from the official SAM 2 repository (https://github.com/facebookresearch/sam2); "
        "read the license that accompanies the weights there before use.",
        "- **FFmpeg / FFprobe**: not redistributed. Builds are licensed under LGPL or GPL depending on how they were compiled; check the build you use.",
        "",
        "## Notes",
        "- PyInstaller (GPL-2.0 with an exception for the bootloader) is the tool that produced the executables; its license allows distributing the result.",
        "- Qt for Python is used through dynamic linking (shared libraries inside `_internal`), which is what its LGPL option requires; "
        "to replace the Qt libraries, replace the files in `_internal`.",
        "- If a row says the license is not declared, the package metadata does not state it; look at the upstream project before distributing.",
    ]
    if missing:
        lines += ["", "Packages listed above that were not installed when this file was generated: " + ", ".join(missing)]
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(rows)} packages" + (f", missing: {missing}" if missing else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "THIRD_PARTY_NOTICES.md")))
